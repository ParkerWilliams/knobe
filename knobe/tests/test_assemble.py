_FAMILY_ASSEMBLY_FIELDNAMES = [
    "family_id", "domain", "valence", "nonmoral_subdomain", "agent", "goal",
    "common_action", "uncommon_action", "affected_entity",
    "low_evocative_outcome", "high_evocative_outcome", "outcome_verb",
]


def _write_family_csv(path: Path, families: list[dict], extra_fieldnames: list[str] | None = None) -> None:
    fieldnames = _FAMILY_ASSEMBLY_FIELDNAMES + (extra_fieldnames or [])
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(families)


def _two_family_matrix() -> list[dict]:
    return [
        _valid_family(family_id="TST-MB-01", valence="MB"),
        _valid_family(
            family_id="TST-MG-01", valence="MG",
            low_evocative_outcome="a report showed the build had passed",
            high_evocative_outcome="teammates were able to ship the release on schedule",
            outcome_verb="stabilize the shared build",
        ),
    ]


