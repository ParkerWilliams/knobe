class TestGoldenFile:
    def test_golden_file_committed_and_nonempty(self):
        assert GOLDEN_CSV.exists()
        assert GOLDEN_CSV.stat().st_size > 0

    def test_assemble_matches_legacy_golden_bytes(self, tmp_path):
        families = assemble.load_families(MASTER_MATRIX)
        rows = assemble.assemble(families)
        validated_rows = [VignetteRow(**row) for row in rows]

        out_csv = tmp_path / "vignettes_105.csv"
        assemble.write_csv(validated_rows, out_csv)

        produced = out_csv.read_bytes()
        expected = GOLDEN_CSV.read_bytes()
        assert produced == expected

    def test_golden_has_crlf_line_endings(self):
        """Pin the exact byte-level detail that would be lost by a
        text-mode / parsed-row comparison: csv.DictWriter's default
        dialect uses \\r\\n line terminators."""
        data = GOLDEN_CSV.read_bytes()
        assert b"\r\n" in data
        assert data.count(b"\r\n") == data.count(b"\n")  # every \n is part of \r\n

    def test_assembled_rows_count_and_shape(self):
        families = assemble.load_families(MASTER_MATRIX)
        assert len(families) == 105
        rows = assemble.assemble(families)
        assert len(rows) == 420  # 105 families x 4 variants (incl. NEU, spec §3.2)

    def test_assembled_output_passes_vignette_row_schema(self):
        """Requirement 5: after assembling, rows are validated as
        VignetteRows before write; the 105-matrix path must pass."""
        families = assemble.load_families(MASTER_MATRIX)
        rows = assemble.assemble(families)
        validated = [VignetteRow(**row) for row in rows]
        assert len(validated) == 420

    def test_real_matrix_has_no_validation_errors(self):
        families = assemble.load_families(MASTER_MATRIX)
        all_errors = []
        for i, fam in enumerate(families, start=2):
            errs, _warns = assemble.validate_family(fam, i)
            all_errors.extend(errs)
        assert all_errors == []


