def run(
    input_path: str | Path,
    out_prefix: str | Path,
    *,
    force: bool = False,
    release: str | None = None,
    curated: str | Path | None = None,
    changelog: str = "",
    gates_passed: Sequence[str] | None = None,
    release_root: str | Path | None = None,
) -> int:
    """Full assemble pipeline: load -> validate -> assemble -> validate
    output against VignetteRow -> write csv/xlsx/preview -> optionally
    write a release. Returns a process-style exit code (0 success, 1
    failure) rather than raising, except ``ReleaseError`` from a refused
    ``--release`` is caught and reported the same way."""
    input_path = Path(input_path)

    families = load_families(input_path)
    print(f"Loaded {len(families)} family rows from {input_path}")

    all_errors: list[str] = []
    all_warnings: list[str] = []
    for i, fam in enumerate(families, start=2):  # +2: header is row 1
        errs, warns = validate_family(fam, i)
        all_errors.extend(errs)
        all_warnings.extend(warns)

    if all_warnings:
        print(f"\n{len(all_warnings)} WARNING(S) -- worth a human eyeball, but not blocking:")
        for w in all_warnings:
            print(" -", w)

    if all_errors:
        print(f"\n{len(all_errors)} VALIDATION ERROR(S) -- fix these in the spreadsheet before re-running:")
        for e in all_errors:
            print(" -", e)
        if not force:
            print("\nNo output written. (Pass --force to write anyway, if you want to inspect partial output.)")
            return 1
        print("\n--force passed: writing output despite the errors above.")

    rows = assemble(families)
    print(f"Assembled {len(rows)} vignette variants from {len(families)} families.")

    try:
        validated_rows = [VignetteRow(**row) for row in rows]
    except PydanticValidationError as exc:
        print(f"\nASSEMBLED OUTPUT FAILED SCHEMA VALIDATION (spec §7.3) -- no output written:\n{exc}")
        return 1

    csv_path = Path(f"{out_prefix}.csv")
    write_csv(validated_rows, csv_path)
    print(f"Wrote {csv_path}")

    xlsx_path = Path(f"{out_prefix}.xlsx")
    if write_xlsx(families, rows, xlsx_path):
        print(f"Wrote {xlsx_path}")
    else:
        print("openpyxl not installed -- skipped .xlsx output")

    preview_path = Path(f"{out_prefix}_preview.txt")
    render_preview(families, rows, preview_path)
    print(
        f"Wrote {preview_path} -- one example variant per family, for manual read-through "
        f"(automated checks only catch structural fit, not whether it reads well)"
    )

    if release:
        try:
            release_dir = build_release(
                release=release,
                input_path=input_path,
                curated_path=Path(curated) if curated else None,
                validated_rows=validated_rows,
                n_families=len(families),
                changelog=changelog,
                gates_passed=gates_passed,
                release_root=Path(release_root) if release_root else None,
            )
        except ReleaseError as exc:
            print(f"\nRELEASE REFUSED: {exc}")
            return 1
        print(f"Wrote release {release_dir}")

    return 0
