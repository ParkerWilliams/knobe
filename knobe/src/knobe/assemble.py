"""S2: the deterministic vignette assembler (master spec §3.2; WO-2 Part A).

Behavior-preserving port of ``repotentialexperiments/assemble_vignettes.py``.
Every constant it needs (banned-word lists, aliases, the scenario/question
templates, variant letters, output field order) lives in ``constants.py``
and is imported from there -- nothing here redefines a competing copy
(common-context.md constraint 2, master spec §7.2).

Architecture (unchanged from the legacy script):
    SPREADSHEET (authoring layer, human-edited)
        -> load_families + validate_family (this module, deterministic, no LLM calls)
        -> assemble/build_variant
        -> vignettes.csv / .xlsx / preview.txt (pipeline artifacts)

``vignettes.csv`` output is required to be byte-identical to the legacy
script's output for the same input (spec §3.2, WO-2 acceptance criterion);
see ``tests/test_assemble.py``'s golden-file test, which compares raw bytes
against ``tests/golden/vignettes_105.csv`` (generated by actually running
the legacy script against the real 105-family matrix).

This module additionally adds ``--release`` mode (WO-2 Part A requirement
3): writes a frozen ``vignettes.csv`` + ``manifest.json`` into
``data/release/vX.Y/`` after verifying every family is human-approved and
every variant has an accepted curation row. Nothing is written if either
gate fails, and an existing release directory is never overwritten
(master spec §7.1's append-only rule).
"""
