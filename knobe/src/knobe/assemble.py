def write_csv(validated_rows: list[VignetteRow], path: str | Path) -> None:
    """Writes vignettes.csv. Delegates the actual write to
    ``schemas.write_csv_validated`` so exactly one place in the package owns
    the byte-for-byte CSV-writing behavior (csv.DictWriter defaults: line
    endings, quoting) that the golden-file test in tests/test_assemble.py
    checks against the legacy script's real output."""
    write_csv_validated(validated_rows, path, VignetteRow)


def write_xlsx(families: list[dict], rows: list[dict], path: str | Path) -> bool:
    """Writes the two-sheet workbook (master_matrix + vignettes). Returns
    False (writes nothing) if openpyxl isn't installed -- it's an optional
    dependency (pyproject.toml already lists it as a base dependency, but
    this module tolerates its absence like the legacy script did)."""
    if openpyxl is None:
        return False
    wb = openpyxl.Workbook()
    ws1 = wb.active
    ws1.title = "master_matrix"
    mm_fields = FamilyRow.csv_fieldnames()  # the 12 canonical master_matrix columns
    ws1.append(mm_fields)
    for fam in families:
        ws1.append([fam.get(f, "") for f in mm_fields])

    ws2 = wb.create_sheet("vignettes")
    ws2.append(constants.OUTPUT_FIELDNAMES)
    for r in rows:
        ws2.append([r.get(f, "") for f in constants.OUTPUT_FIELDNAMES])

    wb.save(str(path))
    return True


def render_preview(families: list[dict], rows: list[dict], path: str | Path) -> None:
    """Writes one fully-composed variant per family (the 'A' variant) to a
    plain-text file for manual read-through -- the backstop for anything
    the mechanical checks in check_grammatical_fit() can't catch (awkward
    phrasing, subtly wrong verb forms, tone). Automated checks catch
    whether a string FITS the slot; a human still has to judge whether it
    READS WELL once it does."""
    by_family: dict[str, list[dict]] = {}
    for r in rows:
        by_family.setdefault(r["family_id"], []).append(r)

    with open(path, "w", encoding="utf-8") as f:
        for fam in families:
            fid = fam.get("family_id", "?")
            variant_a = next((r for r in by_family.get(fid, []) if r["variant_id"].endswith("-A")), None)
            if not variant_a:
                continue
            f.write(f"=== {fid} ({fam.get('valence', '?')}) ===\n")
            f.write(variant_a["scenario"] + "\n")
            f.write(f"  Q1: {variant_a['q_intentionality']}\n")
            f.write(f"  Q2: {variant_a['q_blame']}\n\n")


