def _repo_root() -> Path:
    """Repo root, derived from this source file's location (works for the
    editable install this package is always run from)."""
    return Path(__file__).resolve().parents[2]


def _default_release_root() -> Path:
    """``data/release/`` under the repo root -- NOT the caller's cwd, so
    ``knobe assemble --release ...`` writes to the right place regardless
    of the directory it's invoked from."""
    return _repo_root() / "data" / "release"


def _git_commit_hash(repo_root: Path) -> str:
    result = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=repo_root, capture_output=True, text=True,
    )
    if result.returncode != 0:
        raise ReleaseError(
            f"could not determine git_commit via `git rev-parse HEAD` in {repo_root}: "
            f"{result.stderr.strip()}"
        )
    return result.stdout.strip()


def _truthy(v) -> bool:
    """Same coercion semantics as ``schemas._coerce_bool`` (true/1/yes,
    case-insensitive; everything else -- including missing -- is False),
    duplicated locally as a tiny helper rather than reaching into that
    module's private function. This is ordinary truthy-string parsing, not
    a frozen scientific instrument, so a small local copy is fine."""
    if isinstance(v, bool):
        return v
    if v is None:
        return False
    return str(v).strip().lower() in ("true", "1", "yes")


def _check_family_approval(input_path: Path) -> list[str]:
    """Returns the family_ids of every family row lacking
    ``human_approved == True``.

    Deliberately does NOT round-trip the raw file through
    ``schemas.FamilyRow`` (which has ``extra="forbid"``): a matrix that
    carries any authoring-only column beyond the 12 canonical ones (e.g.
    "authoring_notes") would then crash release mode with a raw
    ``ValidationError`` instead of refusing cleanly, or worse, would block
    an otherwise-fine release entirely. Instead this reuses
    ``_normalize_header`` -- the same ALIASES-based, tolerant header
    mapping ``load_families`` uses for assembly -- to locate the
    ``family_id`` column, plus a light direct scan for a literal
    ``human_approved`` header (not in ``constants.ALIASES``, since it's a
    WO-1 provenance column, not one of the legacy 12). A matrix without
    the column at all means every row defaults to unapproved, per the
    brief.

    Raises ``ReleaseError`` (never a raw exception) if ``input_path`` isn't
    a .csv, is empty, or has no recognizable family_id column -- release
    mode's provenance check only supports .csv input; assemble .xlsx
    normally, then re-run with ``--release`` against an exported .csv."""
    input_path = Path(input_path)
    if input_path.suffix.lower() != ".csv":
        raise ReleaseError(
            f"--release mode requires CSV input for the human_approved provenance check "
            f"(got {input_path.name!r}, a {input_path.suffix or '(no extension)'} file). "
            f"Assemble from .xlsx normally, then re-run --release against an exported .csv."
        )

    with open(input_path, newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    if not rows:
        raise ReleaseError(f"{input_path} is empty -- cannot check human_approved.")
    headers, data_rows = rows[0], rows[1:]

    mapping = _normalize_header(headers)
    family_id_idx = next((i for i, canonical in mapping.items() if canonical == "family_id"), None)
    if family_id_idx is None:
        raise ReleaseError(f"{input_path} has no recognizable family_id column.")
    approved_idx = next(
        (i for i, h in enumerate(headers) if h is not None and str(h).strip().lower() == "human_approved"),
        None,
    )

    unapproved = []
    for row in data_rows:
        if row is None or all(c is None or str(c).strip() == "" for c in row):
            continue  # skip blank rows, matching load_families
        family_id = row[family_id_idx].strip() if family_id_idx < len(row) else "?"
        approved = _truthy(row[approved_idx]) if approved_idx is not None and approved_idx < len(row) else False
        if not approved:
            unapproved.append(family_id)
    return unapproved


def _check_curation_acceptance(variant_ids: Sequence[str], curated_path: Path) -> list[str]:
    """Returns the variant_ids that lack an ``accepted == True`` row in
    curated_path."""
    curated_rows = read_csv_validated(curated_path, CuratedRow)
    accepted = {r.variant_id for r in curated_rows if r.accepted}
    return [v for v in variant_ids if v not in accepted]


def _labeled_counts(
    validated_rows: list[VignetteRow], *, key: Callable[[VignetteRow], str]
) -> dict[str, LabeledCount]:
    """Groups ``validated_rows`` by ``key(row)`` (valence or domain) and
    reports BOTH levels per group, per docs/DECISIONS_FOR_HUMANS.md item
    (d2) (researcher directive, 2026-07-28): variant count (every row in
    the group) and family count (the number of DISTINCT family_ids in the
    group -- valence/domain are family-level attributes inherited
    unchanged into every variant, so counting distinct family_ids here is
    exact and doesn't need the raw family list or any assumption about how
    many variants a family produces)."""
    variant_counts = Counter(key(r) for r in validated_rows)
    family_ids_by_group: dict[str, set[str]] = {}
    for r in validated_rows:
        family_ids_by_group.setdefault(key(r), set()).add(r.family_id)
    return {
        group: LabeledCount(families=len(family_ids_by_group[group]), variants=variant_counts[group])
        for group in variant_counts
    }


def build_release(
    *,
    release: str,
    input_path: Path,
    curated_path: Path | None,
    validated_rows: list[VignetteRow],
    n_families: int,
    changelog: str = "",
    gates_passed: Sequence[str] | None = None,
    release_root: Path | None = None,
    git_commit: str | None = None,
) -> Path:
    """Writes ``vignettes.csv`` + ``manifest.json`` into
    ``release_root/release/``, after verifying:
      - every family in ``input_path`` has ``human_approved == True``, and
      - ``curated_path`` is supplied and every variant_id in
        ``validated_rows`` has an ``accepted == True`` row in it.
    Raises ``ReleaseError`` (nothing written) if either gate fails, or if
    the release directory already exists (master spec §7.1's append-only
    rule -- releases are never overwritten)."""
    release_root = release_root if release_root is not None else _default_release_root()
    release_dir = Path(release_root) / release

    if release_dir.exists():
        raise ReleaseError(
            f"release directory {release_dir} already exists -- releases are append-only "
            f"(master spec §7.1); cut a new release instead of overwriting."
        )

    unapproved = _check_family_approval(Path(input_path))
    if unapproved:
        raise ReleaseError(
            f"refusing release {release!r}: {len(unapproved)} family row(s) lack "
            f"human_approved == True: {unapproved}"
        )

    if curated_path is None:
        raise ReleaseError(f"refusing release {release!r}: --curated is required for --release mode.")

    missing = _check_curation_acceptance([r.variant_id for r in validated_rows], Path(curated_path))
    if missing:
        raise ReleaseError(
            f"refusing release {release!r}: {len(missing)} variant(s) lack an accepted == True "
            f"row in {curated_path}: {missing}"
        )

    git_commit = git_commit if git_commit is not None else _git_commit_hash(_repo_root())

    release_dir.mkdir(parents=True)
    csv_path = release_dir / "vignettes.csv"
    write_csv(validated_rows, csv_path)

    sha256 = hashlib.sha256(csv_path.read_bytes()).hexdigest()
    by_valence = _labeled_counts(validated_rows, key=lambda r: r.valence)
    by_domain = _labeled_counts(validated_rows, key=lambda r: r.domain)

    manifest = ReleaseManifest(
        release=release,
        created=datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        git_commit=git_commit,
        files={"vignettes.csv": FileManifestEntry(sha256=sha256, rows=len(validated_rows))},
        counts=ReleaseCounts(
            families=n_families, variants=len(validated_rows),
            by_valence=by_valence, by_domain=by_domain,
        ),
        gates_passed=list(gates_passed) if gates_passed else [],
        changelog=changelog,
    )
    (release_dir / "manifest.json").write_text(manifest.model_dump_json(indent=2) + "\n", encoding="utf-8")

    return release_dir


