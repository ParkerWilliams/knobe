# Ingestion -- ported from assemble_vignettes.py's load_families/_normalize_header
# ---------------------------------------------------------------------------


def _normalize_header(raw_headers) -> dict[int, str]:
    """Map arbitrary spreadsheet headers onto the canonical field names via
    ``constants.ALIASES`` (case-insensitive). Returns {col_index: canonical_name}."""
    lookup: dict[str, str] = {}
    for canonical, variants in constants.ALIASES.items():
        for v in variants:
            lookup[v.lower().strip()] = canonical

    mapping: dict[int, str] = {}
    for i, h in enumerate(raw_headers):
        if h is None:
            continue
        key = str(h).lower().strip()
        if key in lookup:
            mapping[i] = lookup[key]
    return mapping


def load_families(path: str | Path, sheet_name: str = "master_matrix") -> list[dict]:
    """Load family rows from an .xlsx (preferring ``sheet_name``, falling
    back to the first sheet) or a .csv. Returns a list of dicts keyed by
    canonical field names (only the 12 assembly columns known via
    ``constants.ALIASES`` -- provenance columns like ``human_approved`` are
    read separately, by a light direct scan, by the release-mode checks
    below (see ``_check_family_approval``))."""
    path = Path(path)
    ext = path.suffix.lower()

    if ext in (".xlsx", ".xlsm"):
        if openpyxl is None:
            raise RuntimeError("openpyxl is required to read .xlsx input")
        wb = openpyxl.load_workbook(path, data_only=True)
        ws = wb[sheet_name] if sheet_name in wb.sheetnames else wb[wb.sheetnames[0]]
        rows = list(ws.iter_rows(values_only=True))
        headers, data_rows = rows[0], rows[1:]
    elif ext == ".csv":
        with open(path, newline="", encoding="utf-8") as f:
            reader = list(csv.reader(f))
        headers, data_rows = reader[0], reader[1:]
    else:
        raise ValueError(f"Unsupported input file type: {ext}")

    mapping = _normalize_header(headers)
    unmapped = [h for i, h in enumerate(headers) if i not in mapping and h]
    if unmapped:
        print(f"NOTE: columns not recognized and ignored: {unmapped}")

    families = []
    for row in data_rows:
        if row is None or all(c is None or str(c).strip() == "" for c in row):
            continue  # skip blank rows
        d = {}
        for i, val in enumerate(row):
            if i in mapping:
                d[mapping[i]] = "" if val is None else str(val).strip()
        families.append(d)
    return families


