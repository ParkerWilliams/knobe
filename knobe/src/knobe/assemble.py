def _lower_agent(agent: str) -> str:
    if agent.startswith("The "):
        return "the " + agent[4:]
    return agent[0].lower() + agent[1:] if agent else agent


def build_variant(fam: dict, typicality: str, evocativeness: str) -> dict:
    agent = fam["agent"]
    action = fam["common_action"] if typicality == "common" else fam["uncommon_action"]
    outcome_text = fam["low_evocative_outcome"] if evocativeness == "low" else fam["high_evocative_outcome"]
    outcome_verb = fam["outcome_verb"]
    goal = fam["goal"]
    affected = fam["affected_entity"]

    scenario = constants.SCENARIO_TEMPLATE.format(
        agent=agent, action=action, goal=goal, affected=affected,
        outcome_verb=outcome_verb, outcome_text=outcome_text,
    )

    agent_lower = _lower_agent(agent)
    q_intentionality = constants.Q_INTENTIONALITY_TEMPLATE.format(
        agent_lower=agent_lower, outcome_verb=outcome_verb,
    )

    letter = constants.VARIANT_LETTER[(typicality, evocativeness)]
    row = {
        "variant_id": f"{fam['family_id']}-{letter}",
        "family_id": fam["family_id"],
        "domain": fam["domain"],
        "valence": fam["valence"],
        "nonmoral_subdomain": fam.get("nonmoral_subdomain", ""),
        "sign": constants.SIGN_BY_VALENCE[fam["valence"]],
        "typicality": typicality,
        "evocativeness": evocativeness,
        "scenario": scenario,
        "q_intentionality": q_intentionality,
    }
    for qkey, template in constants.QUESTIONS.items():
        row[qkey] = template.format(agent_lower=agent_lower)
    return row


def assemble(families: list[dict]) -> list[dict]:
    rows = []
    for fam in families:
        for typicality in ("common", "uncommon"):
            for evocativeness in ("low", "high"):
                rows.append(build_variant(fam, typicality, evocativeness))
    return rows


